<p>　　深度療癒力作《麻醉醫師靈魂所在的地方》推出之後，主動脈正處於人生最好的階段，但是這個狀態讓他深感不安，因為身為一個醫師必須做很多影響人的決定，為了保持自己的真心，他決定「停止」……</p>
<p>　　2022年初，麻醉醫師主動脈脫下白袍去禪寺進修，深信「坐在眾生的苦難之中就是解脫的開始。」更冀望禪修能讓他從人生這場大夢醒來！</p>
<p>　　身旁的人不懂他為何宛如苦行僧般生活，《心安的練習》記錄了他一邊修行一邊行醫的省思，是自我自叩問，也是給眾人的回覆：</p>
<p>　　「禪修是以一種身體健康的狀態，走過猶如地獄的諸多折磨，<br>
　　當你都能平靜地度過一切，你已經不再是過去的你，<br>
　　如此以全新的姿態重新面對娑婆世界，心就能夠自由。」</p>
<p>　　為了探索人生的新可能，主動脈某種程度勢必要捨棄現在擁有的，喜歡的事情不能做，就好像要斷去自己的一手一腳，或許自覺還是有某種程度的弱點，無法一次完全捨棄，還是需要錢跟最基本的經濟來源，於是他目前幻想中理想的生活典型就是：在禪寺裡面禮拜、掃地、讀經，然後接到電話有急診刀的時候，跟佛陀及師父告假，下山麻兩台刀。</p>
<p>　　    師父對他說：為了利益眾生，可以暫時捨下成佛的腳步……然後且走且丟，過著半醫半僧的生活，直到有一天完全成為一個僧人，或者是證明了他沒辦法成為一個僧人，到那時他就算回到娑婆世界，帶著佛教的訓練跟戒律，也更能夠坦然自在地面對一切。</p>
<p>　　人生是一趟單向的旅程，旅程的路上有各種不同的風景，有歡樂也有悲傷，主動脈所描寫的醫病實況、禪修的心得，就好像是他眼裡所看到、所經歷的那一幕幕風景，不管季節如何變動，時間如何長遠，他們都會一直影響著他的心，以及所有讀者的心。</p>
