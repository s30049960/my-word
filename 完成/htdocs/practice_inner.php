<h4>　　▍各界佳潮</h4>
<p>　　我邊讀邊在心裡尖叫，這個麻醉科醫師未免也太仁慈並且太痛苦了，他要如何繼續在這永無止境的輪迴場域中，一次又一次地死去活來。──王蘭芬，專職寫作者</p>
<p>　　若說癌症疼痛是有期徒刑，那頑固的慢性疼痛就是無期徒刑了，苦痛綿延無絕期！除了想盡一切辦法使用止痛藥物，幫病人做神經阻斷神經調控等介入性疼痛治療，嘗試緩解無窮盡的疼痛外，很重要的是：我們聆聽，我們陪伴，我們愛講話。──林至芃，台大醫院麻醉部疼痛科主任、台灣疼痛醫學會理事長</p>
<p>　　主動脈除了是人體裡「靈魂所在的地方」，其解剖學上的特異之處在於主動脈弓幾近一百八十度的髮夾彎構造，新近的研究認為或與動脈系統共振機制有關，可能為了增大血壓脈波的振幅而有此轉彎與共鳴的區域。因此主動脈含有探究人性本質與生命轉彎的多層次寓意。──林沛宇，南部小城外科醫師</p>
<p>　　認識主動脈醫師多年，一開始他是一位穿著白袍的攝影師，每每在生命戰場的最前線記錄著動魄的時刻，在我心中有座普立茲獎，非他莫屬，後來他變成穿著白袍的佛弟子，從大口喝酒吃肉，轉變成佛法菜根香，唯一不變的是他那顆悲天憫人的心，而他的天，也越發遼闊了……──黃誠澤，復安牙醫院長</p>
