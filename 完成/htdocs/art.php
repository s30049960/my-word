<center><h4>彼此身為人的存在</h4></center>
<center><h4>全球暢銷經典《愛的藝術》作者佛洛姆</h4></center>
<center><h4>教你如何獲得真正的富足與快樂</h4></center>
<p>　　在1974年到1976年間，佛洛姆撰寫了《擁有還是存在？》（To Have or to Be?）。實際出版時有一部分內容未隨之刊行，本書便是來自這些未收錄的內容。</p>
<p>　　佛洛姆認為「存在的藝術」指的是「基於真實自我意識的生活方式」，可說是人生的最終目標，必須藉由誠實的自我分析方能實現。</p>
<p>　　在《存在的藝術》中，他以自身的經驗與理解，具體闡述學習「存在的藝術」所需採取的「邁向存在的步驟」。本書前半部討論當代社會的高度消費性，使得人們容易將「擁有」視為滿足需求的唯一指標；後半部則簡述如何藉由覺察和自我分析來實踐「生活的藝術」，從而達到真正的快樂與幸福。</p>
<p>　　保持覺察並練習專注，可說是學習「存在的藝術」的關鍵步驟。佛洛姆強調的「覺察」，是指高度集中的注意力，可以對自己的身體或心靈狀態進行自我觀察。唯有透過覺察，我們才能獲得對自己的獨立思考，不被非理性權威和偶像所左右。</p>
<p>　　佛洛姆認為，權力和名聲固然具有催眠般的魅力，但比起物質上的虛假，更可怕的是人類在追求幸福、內在成長和快樂時所遭遇的虛假。他提醒我們不要輕信那些宣稱可以快速改變個人性格或成就自我實現的課程。相反地，我們應該勇於面對孤獨和痛苦，並將自己的所有能量投入到追求真正目標的道路上。</p>
<h4>本書特色</h4>
<p>　　雖然本書篇幅不多，還曾是另一本書的未刊行手稿，但佛洛姆字字珠璣，對於現代人對自我滿足的種種弊病觀察皆一針見血，從心理、哲學、社會等面向分析，並融合自我分析，兼具理論與實踐，在半世紀後讀來仍十分受用，毫無過時之感。</p>
