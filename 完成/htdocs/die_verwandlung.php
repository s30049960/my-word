<h4>各界好評</h4>

<p>　　不是每個小說家都能如他讓人強烈感受「卡夫卡的世界」。這使得我們在其中的觀看與感受，與自己所在的世界，亦產生疏離。這疏離感，同時讓我們不得不面對生存本質的問題。──朱嘉漢</p>
<p>　　在2019年的當今，「變形」早已是常態。但我仍經常在尋常平日的巴士上，超市裡，街道邊，或偶爾誤闖的某一密閉的房間（那裡陰暗彷彿從未有過太陽），忽忽被臉孔帶上蟲之面具的路人所驚。在這光天化日下誰都馱著一具甲殼的全球化時代，卡夫卡的故事不只是昨天的事，更是一則永遠的今天。──言叔夏</p>
<p>　　高中讀完卡夫卡《變形記》時，腦袋好像被颶風橫掃而過一般，天翻地覆：所以，人生究竟是怎麼一回事？這個社會是不是我所看到的模樣？而我，又是誰？不論來到什麼時代，這本書永遠可以逼使我們思考：人生一遭，到底該走去哪裡？──林皇德</p>
<p>　　我們正在進入一個最光明的世界，同時也最黑暗的年代。我們正在進入一個最理性的世界，同時也最為荒謬的時代。細心閱讀卡夫卡的《變形記》，他將為你和盤托出我們這個現代世界看似極度對反、卻又彼此交織纏繞的兩張容顏。──紀金慶</p>
<p>　　強烈推薦這本書給正在追求自我認識，想了解「我是誰？」的你（妳）。──彭如婉</p>

