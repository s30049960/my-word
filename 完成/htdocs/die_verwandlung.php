　　葛雷高的這場蛻變，似乎從一開始就注定走向悲劇。<br>
　　只是想當個平凡人，竟然如此困難。</p>

<h4>本書特色</h4>

<h4>　　一、獨家收錄《變形記》特輯</h4>
<h4>　　˙法蘭茲．卡夫卡小傳</h4>
<p>　　卡夫卡的父親忙於經商，教養嚴厲，使得他自幼與父親感情疏離，卻又深受其無比龐大的權威影響。卡夫卡與父親的關係，不僅反映在他的陰鬱個性，也表現在其作品當中。本書特輯從頭述說卡夫卡的家庭與生平，帶領讀者認識這位文學大師。</p>
<h4>　　˙《變形記》出版祕辛</h4>
<p>　　《變形記》是卡夫卡生前唯一出版的單本小說作品，初版發行前，卡夫卡特別要求出版商：「封面千萬不行畫那隻蟲！」因此，沒人知道主角葛雷高究竟蛻變成了什麼蟲。本書特輯將揭露此一爭論數十年的文學謎團。</p>
<h4>　　˙探索卡夫卡之城──布拉格</h4>
<p>　　在卡夫卡短暫的一生中，幾乎不曾離開過布拉格，這座城市餵養著卡夫卡的思想，兩者不能分開而論。到今天，布拉格儼然成了「卡夫卡之城」，本書特輯帶領讀者遊覽卡夫卡出生故居、老城廣場、羅浮咖啡館、卡夫卡博物館等各大紀念景點。</p>
<h4>　　二、名家譯本．德文直譯．忠於原意的流暢閱讀體驗</h4>
<p>　　卡夫卡的作品時常出現長句、長段落，部分舊譯本有簡化之疑慮。本書譯者現任淡江大學德語系兼任講師，譯文保留卡夫卡的長段落特色，並且流暢完整、忠於原意、生動逼真，無生硬拗口之病。</p>
<h4>　　三、《變形記》──開創現代文學的必讀經典</h4>
<p>　　村上春樹、米蘭．昆德拉、馬奎斯、納博科夫、卡繆、沙特、羅蘭．巴特、蘇珊．桑塔格……無數文學家、思想家皆大力推崇卡夫卡，視之為現代主義文學、存在主義文學的開創者。</p>
