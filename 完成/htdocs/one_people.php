<h4>強力推薦</h4>
<p>　　和斯棓醫師本人，很幸運地有較多的深入互動交流機會，所以很了解他對文字的鑑賞能力有多好。但他對於人，顯然一直有著更高的興趣。這是一本講人的書，寫的是一個有意思的靈魂，和另外22個靈魂碰撞後的疊加與糾纏。──RainDog 雨狗，簡報工作者</p>
<p>　　上本著作《人生路引》中，楊醫師分門別類整理許多書中的智慧，並對應到人生幾個重大課題。這次，他除了讀書，也把守備範圍擴大到「讀人」；透過他的眼睛和人脈圈，我們得以學習到許多人生命的智慧。──張瀞仁 Jill，作家</p>
<p>　　《要有一個人》寫的是「楊斯棓」這一個人，以及他所看到的標竿人物，但隨著閱讀會發現，楊醫師也想說的是：最後，我們不會是孤單一個人。──陳沛穎，文字工作者</p>
<p>　　《要有一個人》，其實是想用一整本書，引發你把這句話接下去。很多人能看見問題，鮮少人願成為答案。藉著這本書，藉著這些偉大的心靈，斯棓期盼我們都能換個說法：要有一個人，那人就是我；若有兩個人，就是你跟我。願你、願我，都成為那個人！──鄭錫懋，「英語自學王」系列作者、講師</p>
<p>　　拜讀楊醫師的《要有一個人》大作，看似用22本書串起的連篇文章，鎔鑄了22個「我就是那個人」──承擔者的利他人生；但細讀每一篇行文，蘊藏了更大量的利他人生，等待讀者逐一開採。可以說，《要有一個人》是一座寶山，不怕人開採，只怕人不採。神奇的是，這取之不盡用之不竭的珍寶，愈往裡面挖，愈感到身心靈富足。──藍麗娟，作家</p>
