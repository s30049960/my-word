<p>　　2020年10月未上市就3刷的 《人生路引》，楊斯棓轉化28本經典好書的智慧，為人引光指路。睽違3年，這次他挑戰了難度高10倍的「讀人」。</p>
<p>　　他在存款甫達一百萬時，「豪擲」93萬，不計回報的捐出。以「要有一個人」的膽識為軸，串起22位在他生命中有重大意義的人，引領讀者，深入其中，了解他們如何抱持「天使不敢走的路，傻瓜一步跨過去」的精神，以及挾著一股「那人就是我」的豪情壯志、敢於一肩扛起重責的擔當，一次又一次化危機為轉機，化不可能為可能。</p>
<p>　　這22個人與書的故事，皆刻印著動人的核心信念，值得細細品讀、反覆思索，為你的人生開啟無限可能！ </p>
