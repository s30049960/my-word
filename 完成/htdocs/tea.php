<p>　　臺灣地理的形成早在冰河時期海水下降、地殼變動時，在歐亞板塊與菲律賓板塊擠壓下形成，歷經無數歲月累積，在人口遷入、天然條件的變遷下，而有現今臺灣原生山茶的現況。臺灣原住民則是最早和原生山茶在生活上並存著密不可分的淵緣與互融關係。山茶分布區域在中央山脈中部以南及東部較低海拔山區，在地理上南投縣有眉原山茶、鳳凰山茶、德化山茶區塊，嘉義縣有阿里山鄉樂野、龍頭山茶區塊，臺東縣有延平鄉永康山區的永康山茶區塊，最後的分布是臺灣原生山茶分布最廣也是量最多的六龜山茶區，由屏東至高雄都有它的生長環境。分析整個臺灣山茶的分布區域，我們發現原住民部落的棲息地和山茶文化有密不可分的生活連結。</p>
<p>　　臺灣茶產業享譽全球，然而以往在臺灣茶史中的報導皆以臺灣茶是早年由中國大陸茶引進至臺灣為主，沒有任何一本專書具體介紹臺灣原生山茶的歷史背景，從歷史文獻考證、從地理環境、茶種鑑定與原住民之山茶文化考察調查撰寫的臺灣原生山茶。</p>
<p>　　2020年「臺灣原生山茶文化學會」正式成立，一致推舉對於臺灣原生山茶投入研究近20年時間的本書作者—鄭子豪先生(本名鄭智誠)擔任第一屆的理事長。以推廣臺灣原生山茶教育文化相關活動；以科學方法製作研究鑑定原生山茶；結合原生山茶與原住民茶文化、現代茶文化之交流，並提升臺灣原生山茶製作水準與產業效益；促進國際茶文化與產業之合作及交流事項；研擬出版原生山茶文化書籍等。</p>
